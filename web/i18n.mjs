export function detectLang(search = "", stored = null, navLangs = []) {
  const q = new URLSearchParams(search).get("lang");
  if (q && DICT[q]) return q;
  if (stored && DICT[stored]) return stored;
  for (const l of navLangs) { const c = String(l).toLowerCase().slice(0, 2); if (DICT[c]) return c; }
  return "en";
}

// t(lang)(chave, {vars}): cai para português se faltar a chave; marcadores {x} em falta ficam vazios
export function makeT(lang) {
  const d = DICT[lang] ?? DICT.en, pt = DICT.pt;
  return (key, vars = {}) => String(d[key] ?? pt[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}
